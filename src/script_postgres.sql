/*
 * creazione d'una stored procedura -- stpe 3
 * con risultato numero di records modificate
*/
drop procedure aumento_stipendio_per_ruolo;
create or replace procedure aumento_stipendio_per_ruolo (
	IN p_min_stipendio numeric,
	IN p_ruolo varchar(100),
	OUT p_numero_record INTEGER
)
language plpgsql
as $$
begin
	update contratto
			set stipendio = stipendio * 1.10
			where stipendio > p_min_stipendio
				and id_contratto in (
					select con.id_contratto from contratto con
						join ruole r on con.id_ruole = r.id_ruole
							where lower(r.descrizione) = lower(p_ruolo) 
				);
	GET DIAGNOSTICS p_numero_record = ROW_COUNT;
	
end;
$$

call aumento_stipendio_per_ruolo(1300, 'sviluppatore', null);

