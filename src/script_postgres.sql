create or replace view list_employee as
	select e.id, e.fullname, e.gender , c.stipendio, c.data_assunzione, 
		   cat.tipo, r.descrizione, r.stipendio_minimo
		from employee e
		left join contratto c on c.id_contratto = e.id_contratto
		left join categorie cat on cat.id_categorie = c.id_categoria
		left join ruole r on r.id_ruole = c.id_ruole
 
