create or replace view list_employee as
	select e.id, e.fullname, e.gender , c.stipendio, c.data_assunzione, 
		   cat.tipo, r.descrizione, r.stipendio_minimo
		from employee e
		left join contratto c on c.id_contratto = e.id_contratto
		left join categorie cat on cat.id_categorie = c.id_categoria
		left join ruole r on r.id_ruole = c.id_ruole
 
select * from list_employee;

/*
 * creazione d'una procedura -- step 2
 */
create or replace function find_employee(stipendio_min numeric)
	returns table (
		id int,
		fullname varchar(50),
		data_assunzione Date,
		stipendio numeric,
		descrizione varchar(100),
		tipo varchar(100)
	) as $$
	begin
		return QUERY
		select e.id, e.fullname, c.data_assunzione, c.stipendio,  
		    cat.tipo,r.descrizione 
		from employee e
		left join contratto c on c.id_contratto = e.id_contratto
		left join categorie cat on cat.id_categorie = c.id_categoria
		left join ruole r on r.id_ruole = c.id_ruole
		where c.stipendio > stipendio_min;
	end;
	$$ language plpgsql;

