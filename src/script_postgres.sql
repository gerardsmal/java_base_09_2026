create or replace trigger trigger_log_employee_insert
	after insert or update or delete on employee
	for each row
		execute function log_employee();

/*
 * definizione della funzione utilizzata dal trigger
 * TG_OP   -> codice operazione DELETE; UPDATE; CREATE
 * new     -> record inserito o aggiornata  
 * 					non disponibile per delete
 * old     -> record eliminate per delete
 * 			  record precedente per update
 * 					non disponibile per INSERT	 
 */
create or replace function log_employee()
	returns trigger
	as $$
	begin
		if TG_OP = 'DELETE' then
			insert into employee_log(id,id_contratto,country,email,fullname,gender,address,action)
				values
			(old.id, old.id_contratto, old.country, old.email, old.fullname, old.gender, old.address, TG_OP);
			return old;
		else
			insert into employee_log(id,id_contratto,country,email,fullname,gender,address,action)
				values
			(new.id, new.id_contratto, new.country, new.email, new.fullname, new.gender, new.address, TG_OP);
			return new;
		end if;	       
	end
	$$ language plpgsql;


