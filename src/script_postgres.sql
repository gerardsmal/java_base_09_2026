 * loop while
 * exit usire del loop
 */
create or replace procedure create_sp_employee(number_emp numeric)
language plpgsql
as $$
declare
	startPay numeric := 36000;
	emp_num  numeric := 0; 
begin
	while (emp_num < number_emp) loop
		emp_num := emp_num + 1;

		if startPay < 1000 then
			exit;
		end if;

		if emp_num % 2 then
			continue;
		end if;

		raise notice 'emp_id %', emp_num;
		insert into sp_employee (annual_salary) values (startPay);
		startPay := startPay - 5000; 

	end loop;
end;
$$;	

