/*
 * restore employee cancelati
 * attenzione:  nel caso d'un employee cancellato non é detto che il contratto é stato cancellato.
 */	
create or replace procedure restore_employee(p_idLog int)	
	language plpgsql
	as $$
	declare
		riga employee_log%ROWTYPE;
		cont contratto_log%ROWTYPE;
	begin
		select * from employee_log into riga where id_log = p_idLog;

		-- control row selectioned
		if not found then
			raise exception 'log % non trovato', p_idLog;
		end if;
		if riga.action::text <> 'DELETE' then
			raise exception 'employee % non in modalità delete', riga.id_log;
		end if;
		
		-- verify contratto
		if riga.id_contratto is not null then
			select * from contratto_log into cont where id_contratto = riga.id_contratto
					and azione = 'DELETE' order by azione_time desc limit 1;
			if found then
				raise notice 'contratto found --- restore --';
				INSERT INTO contratto (data_assunzione, id_categoria, id_contratto, id_ruole, stipendio)
					VALUES(cont.data_assunzione, cont.id_categoria, cont.id_contratto, cont.id_ruolo, cont.stipendio); 

				update contratto_log set azione = 'RESTORED'  where id = cont.id;
			end if;	
		end if;
		
		-- restore employee
		raise notice 'employee found --- restore ---'; 
		INSERT INTO employee (id, id_contratto, country, email, fullname, gender, address)
		          VALUES(riga.id, riga.id_contratto, riga.country, riga.email, riga.fullname, riga.gender, riga.address);

		raise notice 'update log status -------';
		update employee_log set action = 'RESTORED'  where id_log = p_idLog;

	end;
	$$
	
call restore_employee(13);